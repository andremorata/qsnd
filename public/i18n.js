export function resolveLocale(savedLocale, browserLanguages = []) {
  if (SUPPORTED_LOCALES.includes(savedLocale)) return savedLocale;
  return browserLanguages.some((language) => language?.toLowerCase().startsWith('pt')) ? 'pt-BR' : DEFAULT_LOCALE;
}

export function hasTranslation(locale, key) {
  return Object.hasOwn(messages[locale] || {}, key);
}

export function translate(locale, key, values = {}) {
  const template = messages[locale]?.[key] ?? messages[DEFAULT_LOCALE]?.[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match);
}
